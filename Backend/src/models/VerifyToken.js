import mongoose from "mongoose";

const verifyTokenSchema = new mongoose.Schema({
  userId: {
    type: mongoose.Schema.Types.ObjectId,
    ref: "User",
    required: true,
  },
  token: {
    type: String,
    required: true,
    unique: true,
  },
  createdAt: {
    type: Date,
    default: Date.now,
  },
});

const VerifyToken = mongoose.model("VerifyToken", verifyTokenSchema);

export default VerifyToken;
